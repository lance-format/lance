#[test]
fn statistics_extrema_match_baseline() {
    let mut failures = Failures::default();
    for fixture in fixtures() {
        let mut whole = StatisticsAccumulator::new(fixture.input.data_type());
        whole.update(&fixture.input).unwrap();

        // Merging two halves goes through `ArrowScalar` ordering and must agree.
        let split = fixture.len() / 2;
        let mut merged = StatisticsAccumulator::new(fixture.input.data_type());
        merged.update(&fixture.input.slice(0, split)).unwrap();
        let mut rest = StatisticsAccumulator::new(fixture.input.data_type());
        rest.update(&fixture.input.slice(split, fixture.len() - split))
            .unwrap();
        merged.merge(&rest).unwrap();

        let min_pos = fixture.is_nan.iter().position(|nan| !nan);
        let max_pos = fixture.is_nan.iter().rposition(|nan| !nan);
        let nan_count = fixture.is_nan.iter().filter(|nan| **nan).count() as u64;
        let is_float = matches!(
            fixture.input.data_type(),
            DataType::Float16 | DataType::Float32 | DataType::Float64
        );

        for (path, stats) in [
            ("StatisticsAccumulator::update", whole.finish()),
            ("StatisticsAccumulator::merge", merged.finish()),
        ] {
            if stats.null_count != fixture.null_count as u64 {
                failures.check(Err(format!(
                    "fixture {} via {path}: null_count expected {}, got {}",
                    fixture.name, fixture.null_count, stats.null_count
                )));
            }
            if stats.nan_count != is_float.then_some(nan_count) {
                failures.check(Err(format!(
                    "fixture {} via {path}: nan_count expected {:?}, got {:?}",
                    fixture.name,
                    is_float.then_some(nan_count),
                    stats.nan_count
                )));
            }
            for (which, expected_pos, actual) in
                [("min", min_pos, &stats.min), ("max", max_pos, &stats.max)]
            {
                let expected_label = expected_pos.map(|pos| fixture.labels[pos]);
                let actual_identity = actual
                    .as_ref()
                    .map(|scalar| (fixture.identity_of)(scalar.as_array().as_ref(), 0));
                let expected_identity = expected_pos.map(|pos| fixture.identities[pos].clone());
                if actual_identity != expected_identity {
                    failures.check(Err(format!(
                        "fixture {} via {path}: {which} expected {:?} ({:?}), got {:?} ({:?})",
                        fixture.name,
                        expected_label,
                        expected_identity,
                        actual.as_ref().map(|scalar| scalar.to_string()),
                        actual_identity,
                    )));
                }
            }
        }
    }
    failures.finish();
}

/// Signed zeros are the one pair that `==` calls equal and the total order
/// does not. The mixed fixtures above always have the infinities as extrema,
/// so only an input made of zeros shows whether statistics still tell them
/// apart: the baseline is `min = -0.0`, `max = +0.0`, by bit pattern, in
/// either input order and whether the two arrive in one batch or in two
/// accumulators that are merged.
#[rstest]
#[case::f64_neg_first(Arc::new(Float64Array::from(vec![
    f64::from_bits(0x8000_0000_0000_0000),
    f64::from_bits(0),
])))]
#[case::f64_pos_first(Arc::new(Float64Array::from(vec![
    f64::from_bits(0),
    f64::from_bits(0x8000_0000_0000_0000),
])))]
#[case::f32_neg_first(Arc::new(Float32Array::from(vec![
    f32::from_bits(0x8000_0000),
    f32::from_bits(0),
])))]
#[case::f32_pos_first(Arc::new(Float32Array::from(vec![
    f32::from_bits(0),
    f32::from_bits(0x8000_0000),
])))]
#[case::f16_neg_first(Arc::new(Float16Array::from(vec![
    f16::from_bits(0x8000),
    f16::from_bits(0),
])))]
#[case::f16_pos_first(Arc::new(Float16Array::from(vec![
    f16::from_bits(0),
    f16::from_bits(0x8000),
])))]
fn statistics_keep_signed_zeros_apart(#[case] input: ArrayRef) {
    let (identity_of, width) = match input.data_type() {
        DataType::Float64 => (float64().identity_of, 8),
        DataType::Float32 => (float32().identity_of, 4),
        DataType::Float16 => (float16().identity_of, 2),
        other => panic!("unexpected type {other}"),
    };
    // IEEE zeros: every bit clear is `+0.0`; the sign bit alone is `-0.0`.
    // Identities are little-endian, so the sign lands in the last byte.
    let positive_zero = vec![0u8; width];
    let mut negative_zero = vec![0u8; width];
    negative_zero[width - 1] = 0x80;

    let mut whole = StatisticsAccumulator::new(input.data_type());
    whole.update(&input).unwrap();

    // Each value in its own accumulator, merged in input order, goes through
    // `ArrowScalar` ordering rather than the per-batch scan.
    let mut merged = StatisticsAccumulator::new(input.data_type());
    merged.update(&input.slice(0, 1)).unwrap();
    let mut second = StatisticsAccumulator::new(input.data_type());
    second.update(&input.slice(1, 1)).unwrap();
    merged.merge(&second).unwrap();

    for (path, stats) in [
        ("StatisticsAccumulator::update", whole.finish()),
        ("StatisticsAccumulator::merge", merged.finish()),
    ] {
        let min = stats
            .min
            .as_ref()
            .map(|s| identity_of(s.as_array().as_ref(), 0));
        let max = stats
            .max
            .as_ref()
            .map(|s| identity_of(s.as_array().as_ref(), 0));
        assert!(
            min.as_ref() == Some(&negative_zero),
            "{} via {path}: min expected -0.0 ({negative_zero:?}), got {:?} ({min:?})",
            input.data_type(),
            stats.min.as_ref().map(|s| s.to_string()),
        );
        assert!(
            max.as_ref() == Some(&positive_zero),
            "{} via {path}: max expected +0.0 ({positive_zero:?}), got {:?} ({max:?})",
            input.data_type(),
            stats.max.as_ref().map(|s| s.to_string()),
        );
    }
}

fn one_shot(batches: Vec<RecordBatch>, schema: Arc<Schema>) -> Arc<dyn ExecutionPlan> {
    let stream =
        RecordBatchStreamAdapter::new(schema, futures::stream::iter(batches.into_iter().map(Ok)));
    Arc::new(OneShotExec::new(
        Box::pin(stream) as SendableRecordBatchStream
    ))
}

fn sort_expr(opts: SortOptions) -> PhysicalSortExpr {
    PhysicalSortExpr {
        expr: Arc::new(Column::new("value", 0)),
        options: opts,
    }
}

async fn output_rows(plan: Arc<dyn ExecutionPlan>) -> Vec<usize> {
    let stream = execute_plan(plan, LanceExecutionOptions::default()).unwrap();
    let schema = stream.schema();
    let batches: Vec<RecordBatch> = stream.try_collect().await.unwrap();
    let batch = concat_batches(&schema, &batches).unwrap();
    batch
        .column(1)
        .as_primitive::<UInt64Type>()
        .values()
        .iter()
        .map(|&row| row as usize)
        .collect()
}

/// `Scanner::order_by` builds exactly this plan: a `SortExec` with the
/// caller's `SortOptions` over an unsorted input. With a `limit` it becomes a
/// `SortExec` with a fetch, which DataFusion runs as a TopK over the row
/// encoding instead of the sort kernel; a fetch of the full length keeps the
/// whole order visible.
#[tokio::test]
async fn sort_exec_matches_baseline() {
    let mut failures = Failures::default();
    for fixture in fixtures() {
        for opts in ALL_OPTIONS {
            let batch = fixture.value_batch(&fixture.all_rows());
            let input = one_shot(vec![batch.clone()], batch.schema());
            let plan = Arc::new(SortExec::new([sort_expr(opts)].into(), input));
            let rows = output_rows(plan).await;
            failures.check(fixture.check_order("datafusion SortExec", opts, &rows));

            let input = one_shot(vec![batch.clone()], batch.schema());
            let plan = Arc::new(
                SortExec::new([sort_expr(opts)].into(), input).with_fetch(Some(fixture.len())),
            );
            let rows = output_rows(plan).await;
            failures.check(fixture.check_order(
                "datafusion SortExec with fetch (TopK)",
                opts,
                &rows,
            ));
        }
    }
    failures.finish();
}

/// Btree training merges several already-sorted inputs with a
/// `SortPreservingMergeExec` under a `UnionExec`, which compares through
/// DataFusion's merge cursors rather than through a sort kernel. The inputs
/// here are sorted by the baseline, not by arrow, so the merge order is only
/// right if the cursors agree with the baseline.
#[tokio::test]
async fn sort_preserving_merge_matches_baseline() {
    let mut failures = Failures::default();
    for fixture in fixtures() {
        let baseline = fixture.baseline_rows(ASC_NULLS_FIRST);
        let partitions = 3;
        let schema = fixture.value_batch(&[]).schema();
        let inputs: Vec<Arc<dyn ExecutionPlan>> = (0..partitions)
            .map(|partition| {
                let rows: Vec<usize> = baseline
                    .iter()
                    .copied()
                    .skip(partition)
                    .step_by(partitions)
                    .collect();
                one_shot(vec![fixture.value_batch(&rows)], Arc::clone(&schema))
            })
            .collect();
        let union = UnionExec::try_new(inputs).unwrap();
        let plan = Arc::new(SortPreservingMergeExec::new(
            [sort_expr(ASC_NULLS_FIRST)].into(),
            union,
        ));
        let rows = output_rows(plan).await;
        failures.check(fixture.check_order(
            "datafusion SortPreservingMergeExec",
            ASC_NULLS_FIRST,
            &rows,
        ));
    }
    failures.finish();
}
