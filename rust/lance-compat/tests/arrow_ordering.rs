/// The sort used to train every ordered scalar index (btree, bitmap, label
/// list, JSON) and the value of `SortOptions::default()`.
const ASC_NULLS_FIRST: SortOptions = SortOptions {
    descending: false,
    nulls_first: true,
};
const ASC_NULLS_LAST: SortOptions = SortOptions {
    descending: false,
    nulls_first: false,
};
