//! Arrow ordering compatibility fixtures.
//!
//! Lance defines no comparison rules of its own. Scalar indices, column
//! statistics and `ORDER BY` all inherit the total order implemented by Arrow
//! Rust, and by DataFusion on top of it. These tests pin that order with
//! hand-written expectations so that an upgrade which changes it fails here,
//! naming the type, the inputs and both orderings, instead of silently
//! reordering btree pages, zone map extrema or query results.
//!
//! # Baseline
//!
//! Established against `arrow-array`, `arrow-ord` and `arrow-row` 58.4.0 and
//! `datafusion` 54.1.0 on 2026-10-07. The expected orders were written from
//! the IEEE 754 `totalOrder` predicate for floats, two's-complement order for
//! integers, decimals and temporal natives, byte-wise lexicographic order for
//! strings and binary, and `false < true` for booleans. None of them were
//! generated by running Arrow. Special floats are spelled as bit patterns and
//! compared by bit pattern, never by `==`.
//!
//! # Production paths covered
//!
//! | API under test                          | Lance path that relies on it                                   |
//! |-----------------------------------------|----------------------------------------------------------------|
//! | `arrow_ord::sort::sort_to_indices`      | `RecordBatchExt::sort_by_column`; DataFusion `SortExec` on one column, which is how `Scanner::order_by` and btree, bitmap, label-list and JSON index training sort |
//! | `arrow_ord::sort::lexsort_to_indices`   | DataFusion `SortExec` on several columns (`Scanner::order_by`, FTS and vector result ordering) |
//! | `arrow_ord::ord::make_comparator`       | `BTreeLookup::pages_between` and the btree equality fallback   |
//! | `ArrowNativeTypeOp::compare`            | the btree's inlined primitive comparator; DataFusion's single-column merge cursor |
//! | `arrow_row::RowConverter`               | `HashJoiner` keys, `FirstByPk` keys, DataFusion's TopK (`SortExec` with a fetch) and its row-based merge cursor for non-primitive types |
//! | `ArrowScalar` (`arrow_row` encoding)    | `StatisticsAccumulator` extrema (zone map, bloom filter)       |
//! | `StatisticsAccumulator` min/max         | zone map and bloom filter statistics                            |
//! | `OrderableScalarValue` / `ScalarValue`  | btree query bounds; zone map pruning                            |
//! | `SortExec`, with and without a fetch    | `Scanner::order_by`, with `limit` taking the TopK path         |
//! | `SortPreservingMergeExec`               | btree training over several inputs                             |
//!
//! Sorting and aggregate statistics are deliberately distinct contracts: a sort
//! places negative NaNs below `-inf` and positive NaNs above `+inf`, while
//! `StatisticsAccumulator` leaves NaN of either sign out of `min`/`max` and
//! reports it through `nan_count`. Both are pinned.
//!
//! # When a test here fails after a dependency upgrade
//!
//! Do not refresh the expectations to make the build green. The baseline is
//! the contract; a change needs a review that answers, in the PR description:
//!
//! 1. Is it an upstream contract change, an upstream bug fix, or a change in
//!    how Lance calls the API? Cite the arrow-rs or DataFusion release note or
//!    pull request.
//! 2. Which Lance behaviours depend on it? Use the table above.
//! 3. Do persisted structures need compatibility handling? Btree page order,
//!    zone map and bloom filter extrema, and sorted index files written by the
//!    previous version are read by the upgraded one.
//!
//! Only once those are answered should the expectations change, together with
//! regression cases for any newly discovered edge case. The reverse also
//! applies: a passing run shows the covered cases are unchanged, not that every
//! input orders identically.
//!
//! # Deferred: fragment column statistics
//!
//! Fragment-level column statistics and the pruning that reads them are not
//! implemented yet. When they are, add to these fixtures:
//!
//! - identical query results with pruning enabled and disabled,
//! - boundary cases for NaN, signed zero, nulls and strings,
//! - statistics written by the previous supported release and read by the
//!   upgraded one, as checked-in `test_data` fixtures.

