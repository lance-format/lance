#[test]
fn test_encode_matches_released_layout() {
    for (json, hex, text) in ENCODE_CASES {
        let expected = decode_hex(hex);

        let from_value = parse_value(json.as_bytes()).unwrap().to_vec();
        assert_eq!(from_value, expected, "parse_value encoding of {json}");

        let from_str = json.parse::<OwnedJsonb>().unwrap().to_vec();
        assert_eq!(
            from_str, expected,
            "OwnedJsonb::from_str encoding of {json}"
        );

        assert_eq!(
            RawJsonb::new(&expected).to_string(),
            *text,
            "decoding of {json}"
        );
    }
}

#[test]
fn test_duplicate_object_key_is_rejected() {
    assert!(parse_value(br#"{"a":1,"a":2}"#).is_err());
    assert!(r#"{"a":1,"a":2}"#.parse::<OwnedJsonb>().is_err());
}

