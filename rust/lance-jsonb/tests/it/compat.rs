//! Byte-level compatibility with the JSONB layout that Lance has already
//! written to disk. The expected bytes were produced by the `jsonb` crate
//! 0.5.6 with `default-features = false, features = ["databend"]`, which is
//! the configuration Lance used before vendoring.

use lance_jsonb::OwnedJsonb;
use lance_jsonb::RawJsonb;
use lance_jsonb::parse_value;

fn decode_hex(hex: &str) -> Vec<u8> {
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
        .collect()
}

